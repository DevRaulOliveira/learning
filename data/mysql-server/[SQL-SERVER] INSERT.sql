/* Para ealizar a adição de informações manualmente, é preciso utilizar dois comandos, o INSERT INTO e o VALUES */

A estrutura de adição de informações é a seguinte

  INSERT INTO **TABELA** ( Coluna1,Coluna2,Coluna3...)
    VALUES(InfoColuna1,InfoColuna2,InfoColuna3...);

Exemplo:
  INSERT INTO CLIENTES (Nome,idade,Endereço)
  VALUES('Pedro', 30,Avenida Paulista);
